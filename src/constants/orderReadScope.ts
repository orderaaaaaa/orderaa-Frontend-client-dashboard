export const ORDER_READ_SCOPE = {
  LIVE: 'LIVE',
  WITH_DELETED: 'WITH_DELETED',
} as const;

export type OrderReadScope =
  (typeof ORDER_READ_SCOPE)[keyof typeof ORDER_READ_SCOPE];

export const ORDER_LOOKUP_SURFACE = {
  ALL_ORDERS: 'ALL_ORDERS',
  CUSTOMER_ORDERS_MODAL: 'CUSTOMER_ORDERS_MODAL',
  CUSTOMER_DETAILS_HISTORY: 'CUSTOMER_DETAILS_HISTORY',
  MANUAL_ORDER_CLIENT_HISTORY: 'MANUAL_ORDER_CLIENT_HISTORY',
  CALL_CENTER: 'CALL_CENTER',
  PRINT_ORDERS: 'PRINT_ORDERS',
  SHIPPING_ORDERS: 'SHIPPING_ORDERS',
  HEADER_QUICK_JUMP: 'HEADER_QUICK_JUMP',
  DETAILS_PAGE_FILTER_NAVIGATION: 'DETAILS_PAGE_FILTER_NAVIGATION',
  DETAILS_PAGE_STATISTICS: 'DETAILS_PAGE_STATISTICS',
  DELAYED_ORDERS: 'DELAYED_ORDERS',
  SCANNER_LOOKUPS: 'SCANNER_LOOKUPS',
} as const;

export type OrderLookupSurface =
  (typeof ORDER_LOOKUP_SURFACE)[keyof typeof ORDER_LOOKUP_SURFACE];

export const READ_SCOPE_BY_SURFACE: Record<OrderLookupSurface, OrderReadScope> =
  {
    ALL_ORDERS: ORDER_READ_SCOPE.WITH_DELETED,
    CUSTOMER_ORDERS_MODAL: ORDER_READ_SCOPE.WITH_DELETED,
    CUSTOMER_DETAILS_HISTORY: ORDER_READ_SCOPE.WITH_DELETED,
    MANUAL_ORDER_CLIENT_HISTORY: ORDER_READ_SCOPE.LIVE,
    CALL_CENTER: ORDER_READ_SCOPE.LIVE,
    PRINT_ORDERS: ORDER_READ_SCOPE.LIVE,
    SHIPPING_ORDERS: ORDER_READ_SCOPE.LIVE,
    HEADER_QUICK_JUMP: ORDER_READ_SCOPE.LIVE,
    DETAILS_PAGE_FILTER_NAVIGATION: ORDER_READ_SCOPE.LIVE,
    DETAILS_PAGE_STATISTICS: ORDER_READ_SCOPE.LIVE,
    DELAYED_ORDERS: ORDER_READ_SCOPE.LIVE,
    SCANNER_LOOKUPS: ORDER_READ_SCOPE.LIVE,
  };

export function readScopeParamsOf(surface: OrderLookupSurface): {
  readScope?: OrderReadScope;
} {
  return READ_SCOPE_BY_SURFACE[surface] === ORDER_READ_SCOPE.WITH_DELETED
    ? { readScope: ORDER_READ_SCOPE.WITH_DELETED }
    : {};
}

export function showsDeletedOrders(surface: OrderLookupSurface): boolean {
  return READ_SCOPE_BY_SURFACE[surface] === ORDER_READ_SCOPE.WITH_DELETED;
}
